const STORAGE_KEY = "giloa-tester-language";
const richTextKeys = new Set(["heroTitle", "heroDescription", "speech"]);

function setLanguage(language) {
  const selected = translations[language] ? language : "ko";
  const dictionary = translations[selected];
  document.documentElement.lang = selected === "zh" ? "zh-CN" : selected;

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;
    const value = dictionary[key];
    if (!value) return;
    if (richTextKeys.has(key)) element.innerHTML = value;
    else element.textContent = value;
  });

  document.querySelectorAll(".lang").forEach((button) => {
    const active = button.dataset.lang === selected;
    button.classList.toggle("active", active);
    button.setAttribute("aria-pressed", String(active));
  });

  try { localStorage.setItem(STORAGE_KEY, selected); } catch (_) {}
}

document.querySelectorAll(".lang").forEach((button) => {
  button.addEventListener("click", () => setLanguage(button.dataset.lang));
});

let savedLanguage = "ko";
try { savedLanguage = localStorage.getItem(STORAGE_KEY) || "ko"; } catch (_) {}
setLanguage(savedLanguage);
